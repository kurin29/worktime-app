import 'package:path/path.dart' as p;
import 'package:sqflite/sqflite.dart';

import '../models/app_settings.dart';
import '../models/work_record.dart';

class DatabaseHelper {
  DatabaseHelper._();
  static final DatabaseHelper instance = DatabaseHelper._();
  Database? _db;

  Future<Database> get database async => _db ??= await _open();

  Future<Database> _open() async {
    final path = p.join(await getDatabasesPath(), 'worktime.db');
    return openDatabase(path,
        version: 3, onCreate: _create, onUpgrade: _upgrade);
  }

  Future<void> _create(Database db, int _) async {
    await db.execute('''
      CREATE TABLE settings (
        id INTEGER PRIMARY KEY,
        monthlyBaseSalary REAL NOT NULL DEFAULT 0,
        isFixedSalary INTEGER NOT NULL DEFAULT 1,
        payDaysPerMonth REAL NOT NULL DEFAULT 21.75,
        standardHoursPerDay REAL NOT NULL DEFAULT 8,
        overtimeHourlyRate REAL NOT NULL DEFAULT 0,
        remindTime TEXT NOT NULL DEFAULT '09:00',
        autoFillEnabled INTEGER NOT NULL DEFAULT 1,
        autoCheckTime TEXT NOT NULL DEFAULT '23:00',
        fillClockInTime TEXT NOT NULL DEFAULT '09:00',
        fillClockOutTime TEXT NOT NULL DEFAULT '18:00'
      )
    ''');
    await db.insert('settings', AppSettings.defaults().toMap());
    await db.execute('''
      CREATE TABLE records (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        date TEXT NOT NULL UNIQUE,
        clockIn TEXT,
        clockOut TEXT,
        breakStart TEXT,
        breakEnd TEXT,
        breakMinutes INTEGER NOT NULL DEFAULT 0,
        overtimeMinutes INTEGER NOT NULL DEFAULT 0,
        note TEXT,
        autoGenerated INTEGER NOT NULL DEFAULT 0
      )
    ''');
  }

  Future<void> _upgrade(Database db, int oldV, int newV) async {
    if (oldV < 2) {
      for (final sql in [
        'ALTER TABLE settings ADD COLUMN autoFillEnabled INTEGER NOT NULL DEFAULT 0',
        "ALTER TABLE settings ADD COLUMN autoCheckTime TEXT NOT NULL DEFAULT '23:00'",
        "ALTER TABLE settings ADD COLUMN fillClockInTime TEXT NOT NULL DEFAULT '09:00'",
        "ALTER TABLE settings ADD COLUMN fillClockOutTime TEXT NOT NULL DEFAULT '18:00'",
      ]) {
        await db.execute(sql);
      }
    }
    if (oldV < 3) {
      await db.execute('ALTER TABLE records ADD COLUMN breakStart TEXT');
      await db.execute('ALTER TABLE records ADD COLUMN breakEnd TEXT');
    }
  }

  Future<AppSettings> getSettings() async {
    final db = await database;
    final rows =
        await db.query('settings', where: 'id = 1', limit: 1);
    if (rows.isEmpty) {
      final s = AppSettings.defaults();
      await saveSettings(s);
      return s;
    }
    return AppSettings.fromMap(rows.first);
  }

  Future<void> saveSettings(AppSettings s) async {
    final db = await database;
    await db.insert('settings', s.toMap(),
        conflictAlgorithm: ConflictAlgorithm.replace);
  }

  Future<WorkRecord?> getRecordByDate(String date) async {
    final db = await database;
    final rows = await db.query('records',
        where: 'date = ?', whereArgs: [date], limit: 1);
    return rows.isEmpty ? null : WorkRecord.fromMap(rows.first);
  }

  Future<List<WorkRecord>> getRecordsForMonth(DateTime m) async {
    final db = await database;
    final s = DateTime(m.year, m.month, 1);
    final e = DateTime(m.year, m.month + 1, 1);
    final rows = await db.query('records',
        where: 'date >= ? AND date < ?',
        whereArgs: [_fmt(s), _fmt(e)],
        orderBy: 'date ASC');
    return rows.map(WorkRecord.fromMap).toList();
  }

  Future<void> upsertRecord(WorkRecord r) async {
    final db = await database;
    final map = r.toMap();
    if (r.id == null) map.remove('id');
    await db.insert('records', map,
        conflictAlgorithm: ConflictAlgorithm.replace);
  }

  Future<void> deleteRecordByDate(String date) async {
    final db = await database;
    await db.delete('records', where: 'date = ?', whereArgs: [date]);
  }

  String _fmt(DateTime d) =>
      '${d.year.toString().padLeft(4, '0')}-'
      '${d.month.toString().padLeft(2, '0')}-'
      '${d.day.toString().padLeft(2, '0')}';
}
