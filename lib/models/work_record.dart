const Object _unset = Object();

class WorkRecord {
  final int? id;
  final String date;
  final String? clockIn;
  final String? clockOut;
  final String? breakStart;
  final String? breakEnd;
  final int breakMinutes;
  final int overtimeMinutes;
  final String? note;
  final bool autoGenerated;
  final int leaveType; // 0:正常, 1:事假, 2:病假, 3:休息日

  WorkRecord({
    this.id,
    required this.date,
    this.clockIn,
    this.clockOut,
    this.breakStart,
    this.breakEnd,
    this.breakMinutes = 0,
    this.overtimeMinutes = 0,
    this.note,
    this.autoGenerated = false,
    this.leaveType = 0,
  });

  static int _m(String v) {
    final p = v.split(':');
    return int.parse(p[0]) * 60 + int.parse(p[1]);
  }

  int get effectiveBreakMinutes {
    if (breakStart != null && breakEnd != null) {
      final s = _m(breakStart!);
      var e = _m(breakEnd!);
      if (e < s) e += 24 * 60;
      return (e - s).clamp(0, 24 * 60);
    }
    return breakMinutes;
  }

  Map<String, dynamic> toMap() => {
        'id': id,
        'date': date,
        'clockIn': clockIn,
        'clockOut': clockOut,
        'breakStart': breakStart,
        'breakEnd': breakEnd,
        'breakMinutes': breakMinutes,
        'overtimeMinutes': overtimeMinutes,
        'note': note,
        'autoGenerated': autoGenerated ? 1 : 0,
        'leaveType': leaveType,
      };

  factory WorkRecord.fromMap(Map<String, dynamic> m) => WorkRecord(
        id: m['id'] as int?,
        date: m['date'] as String,
        clockIn: m['clockIn'] as String?,
        clockOut: m['clockOut'] as String?,
        breakStart: m['breakStart'] as String?,
        breakEnd: m['breakEnd'] as String?,
        breakMinutes: m['breakMinutes'] as int? ?? 0,
        overtimeMinutes: m['overtimeMinutes'] as int? ?? 0,
        note: m['note'] as String?,
        autoGenerated: (m['autoGenerated'] as int? ?? 0) == 1,
        leaveType: m['leaveType'] as int? ?? 0,
      );

  WorkRecord copyWith({
    Object? id = _unset,
    Object? clockIn = _unset,
    Object? clockOut = _unset,
    Object? breakStart = _unset,
    Object? breakEnd = _unset,
    Object? breakMinutes = _unset,
    Object? overtimeMinutes = _unset,
    Object? note = _unset,
    Object? autoGenerated = _unset,
    Object? leaveType = _unset,
  }) {
    return WorkRecord(
      id: identical(id, _unset) ? this.id : id as int?,
      date: date,
      clockIn: identical(clockIn, _unset) ? this.clockIn : clockIn as String?,
      clockOut: identical(clockOut, _unset) ? this.clockOut : clockOut as String?,
      breakStart: identical(breakStart, _unset) ? this.breakStart : breakStart as String?,
      breakEnd: identical(breakEnd, _unset) ? this.breakEnd : breakEnd as String?,
      breakMinutes: identical(breakMinutes, _unset) ? this.breakMinutes : breakMinutes as int,
      overtimeMinutes: identical(overtimeMinutes, _unset) ? this.overtimeMinutes : overtimeMinutes as int,
      note: identical(note, _unset) ? this.note : note as String?,
      autoGenerated: identical(autoGenerated, _unset) ? this.autoGenerated : autoGenerated as bool,
      leaveType: identical(leaveType, _unset) ? this.leaveType : leaveType as int,
    );
  }
}
