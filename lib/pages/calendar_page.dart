import 'package:flutter/material.dart';
import 'package:intl/intl.dart';
import 'package:table_calendar/table_calendar.dart';

import '../db/database_helper.dart';
import '../models/app_settings.dart';
import '../models/work_record.dart';
import '../services/wage_calculator.dart';

class CalendarPage extends StatefulWidget {
  const CalendarPage({super.key});
  @override
  State<CalendarPage> createState() => _CalendarPageState();
}

class _CalendarPageState extends State<CalendarPage> {
  AppSettings? _s;
  Map<DateTime, List<WorkRecord>> _events = {};
  List<WorkRecord> _month = [];
  DateTime _focus = DateTime.now();
  DateTime _selected = DateTime.now();
  bool _loading = true;

  @override
  void initState() {
    super.initState();
    _load(_focus);
  }

  DateTime _d(DateTime d) => DateTime(d.year, d.month, d.day);

  Future<void> _load(DateTime m) async {
    final s = await DatabaseHelper.instance.getSettings();
    final rec = await DatabaseHelper.instance.getRecordsForMonth(m);
    final map = <DateTime, List<WorkRecord>>{};
    for (final r in rec) {
      map.putIfAbsent(_d(DateTime.parse(r.date)), () => []).add(r);
    }
    if (!mounted) return;
    setState(() {
      _s = s;
      _events = map;
      _month = rec;
      _loading = false;
    });
  }

  @override
  Widget build(BuildContext context) {
    if (_loading || _s == null) {
      return const Center(child: CircularProgressIndicator());
    }
    final key = _d(_selected);
    final list = _events[key] ?? [];
    final r = list.isEmpty ? null : list.first;
    final dw = WageCalculator(_s!).calculateDay(r);
    final mw = WageCalculator(_s!).calculateMonth(_month);

    return RefreshIndicator(
      onRefresh: () => _load(_focus),
      child: ListView(
        padding: const EdgeInsets.all(12),
        children: [
          Container(
            padding: const EdgeInsets.all(8),
            decoration: BoxDecoration(
                color: Colors.white, borderRadius: BorderRadius.circular(20)),
            child: TableCalendar<WorkRecord>(
              firstDay: DateTime.utc(2020, 1, 1),
              lastDay: DateTime.utc(2100, 12, 31),
              focusedDay: _focus,
              selectedDayPredicate: (d) => isSameDay(d, _selected),
              availableCalendarFormats: const {CalendarFormat.month: '月'},
              eventLoader: (d) => _events[_d(d)] ?? [],
              onDaySelected: (s, f) => setState(() {
                _selected = s;
                _focus = f;
              }),
              onPageChanged: (f) {
                _focus = f;
                _load(f);
              },
              headerStyle: const HeaderStyle(
                  formatButtonVisible: false,
                  titleCentered: true,
                  titleTextStyle:
                      TextStyle(fontSize: 16, fontWeight: FontWeight.w600)),
              calendarStyle: CalendarStyle(
                todayDecoration: BoxDecoration(
                    color: Theme.of(context)
                        .colorScheme
                        .primary
                        .withOpacity(0.15),
                    shape: BoxShape.circle),
                todayTextStyle: TextStyle(
                    color: Theme.of(context).colorScheme.primary,
                    fontWeight: FontWeight.bold),
                selectedDecoration: BoxDecoration(
                    color: Theme.of(context).colorScheme.primary,
                    shape: BoxShape.circle),
                markersMaxCount: 1,
              ),
              calendarBuilders: CalendarBuilders<WorkRecord>(
                markerBuilder: (_, day, events) {
                  if (events.isEmpty) return null;
                  final auto = events.first.autoGenerated;
                  return Positioned(
                    bottom: 4,
                    child: Container(
                      width: 6,
                      height: 6,
                      decoration: BoxDecoration(
                          color: auto
                              ? const Color(0xFFF59E0B)
                              : const Color(0xFF10B981),
                          shape: BoxShape.circle),
                    ),
                  );
                },
              ),
            ),
          ),
          const SizedBox(height: 12),
          _detail(r, dw),
          const SizedBox(height: 12),
          _monthCard(mw),
        ],
      ),
    );
  }

  Widget _detail(WorkRecord? r, WageResult w) {
    return Container(
      padding: const EdgeInsets.all(18),
      decoration: BoxDecoration(
          color: Colors.white, borderRadius: BorderRadius.circular(20)),
      child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
        Row(children: [
          Text(DateFormat('M月d日 EEEE', 'zh').format(_selected),
              style:
                  const TextStyle(fontSize: 16, fontWeight: FontWeight.w600)),
          const Spacer(),
          if (r != null && r.autoGenerated)
            Container(
              padding:
                  const EdgeInsets.symmetric(horizontal: 8, vertical: 4),
              decoration: BoxDecoration(
                  color: const Color(0xFFFEF3C7),
                  borderRadius: BorderRadius.circular(8)),
              child: const Text('自动补卡',
                  style: TextStyle(
                      fontSize: 11,
                      color: Color(0xFFB45309),
                      fontWeight: FontWeight.w600)),
            ),
        ]),
        const Divider(height: 20),
        if (r == null)
          const Padding(
            padding: EdgeInsets.symmetric(vertical: 12),
            child: Center(
                child: Text('当天暂无记录',
                    style: TextStyle(color: Color(0xFF9CA3AF)))),
          )
        else ...[
          Row(children: [
            Expanded(
                child: _mini('上班', r.clockIn ?? '--', const Color(0xFF3B82F6))),
            Expanded(
                child: _mini('下班', r.clockOut ?? '--', const Color(0xFF10B981))),
            Expanded(
                child: _mini('休息', _break(r), const Color(0xFFF59E0B))),
            Expanded(
                child: _mini('加班', '${r.overtimeMinutes}分',
                    const Color(0xFF6B7280))),
          ]),
          const Divider(height: 20),
          _line('正常工时', '${w.normalHours.toStringAsFixed(2)} 小时'),
          _line('加班工时', '${w.overtimeHours.toStringAsFixed(2)} 小时'),
          _line('底薪', '¥${w.basePay.toStringAsFixed(2)}'),
          _line('加班费', '¥${w.overtimePay.toStringAsFixed(2)}'),
          const Divider(height: 20),
          Row(mainAxisAlignment: MainAxisAlignment.spaceBetween, children: [
            const Text('当天合计',
                style: TextStyle(fontWeight: FontWeight.w600)),
            Text('¥${w.totalPay.toStringAsFixed(2)}',
                style: TextStyle(
                    fontSize: 20,
                    fontWeight: FontWeight.bold,
                    color: Theme.of(context).colorScheme.primary)),
          ]),
        ],
      ]),
    );
  }

  String _break(WorkRecord r) {
    if (r.breakStart != null && r.breakEnd != null) {
      return '${r.breakStart}-${r.breakEnd}';
    }
    if (r.breakStart != null) return '${r.breakStart}-…';
    return r.breakMinutes > 0 ? '${r.breakMinutes}分' : '--';
  }

  Widget _mini(String l, String v, Color c) => Column(children: [
        Text(l,
            style: const TextStyle(fontSize: 11, color: Color(0xFF6B7280))),
        const SizedBox(height: 4),
        Text(v,
            style: TextStyle(
                fontSize: 13, fontWeight: FontWeight.w600, color: c)),
      ]);

  Widget _line(String k, String v) => Padding(
        padding: const EdgeInsets.symmetric(vertical: 4),
        child: Row(
            mainAxisAlignment: MainAxisAlignment.spaceBetween,
            children: [
              Text(k, style: const TextStyle(color: Color(0xFF6B7280))),
              Text(v, style: const TextStyle(fontWeight: FontWeight.w500)),
            ]),
      );

  Widget _monthCard(WageResult w) {
    return Container(
      padding: const EdgeInsets.all(18),
      decoration: BoxDecoration(
        gradient: const LinearGradient(
            colors: [Color(0xFF1E293B), Color(0xFF0F172A)]),
        borderRadius: BorderRadius.circular(20),
      ),
      child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
        Text('${_focus.year}年${_focus.month}月 工资汇总',
            style: const TextStyle(
                color: Colors.white70,
                fontSize: 13,
                fontWeight: FontWeight.w500)),
        const SizedBox(height: 12),
        Row(children: [
          Expanded(
              child: _sumItem(
                  '正常工时', '${w.normalHours.toStringAsFixed(1)}h')),
          Expanded(
              child: _sumItem(
                  '加班工时', '${w.overtimeHours.toStringAsFixed(1)}h')),
        ]),
        const SizedBox(height: 12),
        Row(children: [
          Expanded(
              child: _sumItem('底薪', '¥${w.basePay.toStringAsFixed(0)}')),
          Expanded(
              child: _sumItem('加班费', '¥${w.overtimePay.toStringAsFixed(0)}')),
        ]),
        const Divider(color: Colors.white24, height: 24),
        Row(mainAxisAlignment: MainAxisAlignment.spaceBetween, children: [
          const Text('本月合计',
              style: TextStyle(color: Colors.white70, fontSize: 13)),
          Text('¥${w.totalPay.toStringAsFixed(2)}',
              style: const TextStyle(
                  color: Colors.white,
                  fontSize: 26,
                  fontWeight: FontWeight.bold)),
        ]),
      ]),
    );
  }

  Widget _sumItem(String l, String v) => Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Text(l,
              style: const TextStyle(color: Colors.white54, fontSize: 12)),
          const SizedBox(height: 4),
          Text(v,
              style: const TextStyle(
                  color: Colors.white,
                  fontSize: 16,
                  fontWeight: FontWeight.w600)),
        ],
      );
}
