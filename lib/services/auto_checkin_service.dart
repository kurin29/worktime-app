import 'package:flutter/widgets.dart';
import 'package:intl/intl.dart';
import 'package:workmanager/workmanager.dart';

import '../db/database_helper.dart';
import '../models/work_record.dart';
import 'notification_service.dart';
import 'widget_service.dart';

class AutoCheckInService {
  static const _unique = 'daily_auto_checkin';
  static const _task = 'daily_auto_checkin_task';

  static Future<void> init() => Workmanager().initialize(callbackDispatcher);

  static Future<void> scheduleNext() async {
    final s = await DatabaseHelper.instance.getSettings();
    await Workmanager().cancelByUniqueName(_unique);
    if (!s.autoFillEnabled) return;

    final parts = s.autoCheckTime.split(':').map(int.parse).toList();
    final now = DateTime.now();
    var next = DateTime(now.year, now.month, now.day, parts[0], parts[1]);
    if (!next.isAfter(now)) next = next.add(const Duration(days: 1));

    await Workmanager().registerOneOffTask(
      _unique, _task,
      initialDelay: next.difference(now),
      existingWorkPolicy: ExistingWorkPolicy.replace,
      constraints: Constraints(networkType: NetworkType.notRequired),
    );
  }
}

@pragma('vm:entry-point')
void callbackDispatcher() {
  Workmanager().executeTask((_, __) async {
    WidgetsFlutterBinding.ensureInitialized();
    try { await _runDailyCheck(); } catch (_) {}
    try { await AutoCheckInService.scheduleNext(); } catch (_) {}
    return true;
  });
}

Future<void> _runDailyCheck() async {
  final s = await DatabaseHelper.instance.getSettings();
  if (!s.autoFillEnabled) return;

  final today = DateFormat('yyyy-MM-dd').format(DateTime.now());
  final existing = await DatabaseHelper.instance.getRecordByDate(today);
  if (existing != null && (existing.clockIn != null || existing.clockOut != null)) {
    return;
  }

  final record = (existing ?? WorkRecord(date: today)).copyWith(
    clockIn: s.fillClockInTime,
    clockOut: s.fillClockOutTime,
    autoGenerated: true,
  );
  await DatabaseHelper.instance.upsertRecord(record);
  await WidgetService.refreshFromRecord(record);
  await NotificationService.showAutoCheckInPrompt(today);
}
